static inline const char* uiLangCode(UiLang l) {
    switch (l) {
        case UILANG_VI: return "VI";
        case UILANG_EN: return "EN";
        case UILANG_CN: return "CN";
        default:        return "VI";
    }
}

static inline UiLang uiNextEnabledLang(UiLang cur) {
    const UiLang order[3] = {UILANG_VI, UILANG_EN, UILANG_CN};
    int curIdx = 0;
    for (int i = 0; i < 3; ++i) {
        if (order[i] == cur) { curIdx = i; break; }
    }
    for (int step = 1; step <= 3; ++step) {
        UiLang cand = order[(curIdx + step) % 3];
        if (uiLangEnabled(cand)) return cand;
    }
    return cur;
}

