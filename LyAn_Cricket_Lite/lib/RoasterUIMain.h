static inline int uiBlLevelIndex(uint8_t pct) {
    static const uint8_t kBlSteps[5] = {50, 63, 75, 88, 100};
    int bestIdx = 2;
    int bestDiff = 999;
    for (int i = 0; i < 5; ++i) {
        int d = abs(static_cast<int>(pct) - static_cast<int>(kBlSteps[i]));
        if (d < bestDiff) { bestDiff = d; bestIdx = i; }
    }
    return bestIdx;
}

