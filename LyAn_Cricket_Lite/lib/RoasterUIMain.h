static inline void uiSyncHome() {
    uiUpdateTopRight(g_uiMain.shell, g_uiSnap.batPct, g_uiSnap.batCharging);

    if (!g_uiMain.lblModeSub || !g_uiMain.imgModeIco) return;

    const bool blinkOn = ((millis() / 500UL) % 2UL) == 0;
    const bool modeChanged = (g_uiMain.lastLinkMode != static_cast<int>(g_uiSnap.linkMode));

    // 0 = HiBean (BLE) | 1 = Artisan (WiFi WS:81) | 2 = Web Portal (HTTP:80) | 3 = Standalone
    // Single-color icon (tinted by tone); status text and tone follow the mode
    // HiBean / Artisan: logo in original colors (not tinted); Web Portal: blue; Standalone: cream
    struct ModeLook { const lv_image_dsc_t *(*icon)(); UiTone tone; uint32_t hex; bool native; };
    static const ModeLook kLook[4] = {
        { uiIcon_hibean,    UI_TONE_AMBER, UI_HEX_TEXT, true  },
        { uiIcon_artisan,   UI_TONE_AMBER, UI_HEX_TEXT, true  },
        { uiIcon_globe_lg,  UI_TONE_CYAN,  UI_HEX_CYAN, false },
        { uiIcon_chip_lg,   UI_TONE_AMBER, UI_HEX_TEXT, false },
    };
    const uint8_t lm = (g_uiSnap.linkMode < 4) ? g_uiSnap.linkMode : 3;
    const ModeLook &lk = kLook[lm];
    const bool linked = (lm == 0) ? g_uiSnap.bleConnected : (lm == 1) ? g_uiSnap.artisanConnected
                      : (lm == 2) ? g_uiSnap.webConnected : true;
    if (modeChanged) {
        lv_image_set_src(g_uiMain.imgModeIco, lk.icon());
        uiSetIconColor(g_uiMain.imgModeIco, lk.hex);
        lv_obj_set_style_image_recolor_opa(g_uiMain.imgModeIco, lk.native ? LV_OPA_TRANSP : LV_OPA_COVER, LV_PART_MAIN);
        lv_obj_align(g_uiMain.imgModeIco, LV_ALIGN_TOP_MID, 0, 8);
        lv_obj_set_style_text_color(g_uiMain.lblModeSub, lv_color_hex(UI_HEX_TEXT), LV_PART_MAIN);   // status text always cream
        uiToneBtnSetTone(g_uiMain.btnMode, lk.tone);
        uiToneBtnSetBar(g_uiMain.btnMode, true, false);
        lv_obj_set_style_border_color(g_uiMain.btnMode.btn, lv_color_hex(UI_HEX_ORANGE), LV_PART_MAIN | LV_STATE_PRESSED);   // pressed border: logo orange only
        // Dummy char so the next comparison always differs -> the center label is redrawn (even cleared to empty when switching to HiBean/Alone without a time)
        g_uiMain.lastTopMid[0] = '\x01'; g_uiMain.lastTopMid[1] = '\0';
    }
    {
        const char *want = lm == 3 ? uiTr(STR_STANDALONE) : (linked ? uiTr(STR_CONNECTED) : uiTr(STR_WAIT_CONN));
        if (strcmp(lv_label_get_text(g_uiMain.lblModeSub), want) != 0) lv_label_set_text(g_uiMain.lblModeSub, want);
    }
    lv_obj_set_style_image_opa(g_uiMain.imgModeIco, linked || blinkOn ? LV_OPA_COVER : LV_OPA_20, LV_PART_MAIN);
    g_uiMain.lastLinkMode = g_uiSnap.linkMode;

    // Middle of the top bar:
    // - Artisan (1) / Web Portal (2): IP address <-> HH:MM clock every 10 s (if time is synced)
    // - HiBean (0) / Standalone (3): HH:MM clock when synced
    if (g_uiMain.shell.lblMid) {
        const bool isNetMode  = (g_uiSnap.linkMode == 1 || g_uiSnap.linkMode == 2);
        const bool showClock  = g_uiSnap.clockSynced && (!isNetMode || (((millis() / 10000UL) % 2UL) == 1));
        const char *wantText  = "";
        uint32_t    wantColor = UI_HEX_TEXT;

        if (showClock) {
            wantText  = g_uiSnap.clockStr;
            wantColor = UI_HEX_TEXT;
        } else if (isNetMode) {
            wantText  = g_uiSnap.ipStr;
            wantColor = UI_HEX_ORANGE;   // IP is always logo orange
        }

        if (strcmp(g_uiMain.lastTopMid, wantText) != 0) {
            snprintf(g_uiMain.lastTopMid, sizeof(g_uiMain.lastTopMid), "%s", wantText);
            lv_obj_set_style_text_color(g_uiMain.shell.lblMid, lv_color_hex(wantColor), LV_PART_MAIN);
            lv_label_set_text(g_uiMain.shell.lblMid, wantText);
            if (wantText[0]) uiShellCenterMid(g_uiMain.shell);
        }
    }
}

