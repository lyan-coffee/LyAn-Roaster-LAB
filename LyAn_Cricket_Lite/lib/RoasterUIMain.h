// One-layer A8 icon -> two stacked layers of the same size: the "mask = true" part is tinted hexB, the rest hexA (centered in the parent).
// Buffers come from PSRAM once per icon (no internal RAM); if memory is short the whole icon is drawn in hexA.
typedef bool (*UiIconMaskFn)(int x, int y);
static inline void uiCreateTwoToneIcon(lv_obj_t *parent, const lv_image_dsc_t *src, UiIconMaskFn mask, uint32_t hexA, uint32_t hexB) {
    const int w = src->header.w, h = src->header.h;
    const size_t n = (size_t)w * h;
    struct Cache { const lv_image_dsc_t *key; uint8_t *buf; lv_image_dsc_t dA, dB; };
    static Cache cache[4] = {};
    Cache *c = nullptr;
    for (auto &e : cache) { if (e.key == src) { c = &e; break; } }
    if (!c) {
        for (auto &e : cache) { if (!e.key) { c = &e; break; } }
        if (!c) { lv_obj_t *one = uiCreateIconImg(parent, src, hexA); lv_obj_center(one); return; }
        c->key = src;
        c->buf = static_cast<uint8_t*>(heap_caps_malloc(n * 2, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT));
        if (c->buf) {
            const uint8_t *px = src->data;
            for (int y = 0; y < h; ++y) {
                for (int x = 0; x < w; ++x) {
                    const uint8_t v = px[(size_t)y * w + x];
                    const bool m = mask(x, y);
                    c->buf[(size_t)y * w + x]     = m ? 0 : v;
                    c->buf[n + (size_t)y * w + x] = m ? v : 0;
                }
            }
            c->dA = *src; c->dA.data = c->buf;
            c->dB = *src; c->dB.data = c->buf + n;
        }
    }
    if (!c->buf) { lv_obj_t *one = uiCreateIconImg(parent, src, hexA); lv_obj_center(one); return; }
    lv_obj_t *ia = uiCreateIconImg(parent, &c->dA, hexA); lv_obj_center(ia);
    lv_obj_t *ib = uiCreateIconImg(parent, &c->dB, hexB); lv_obj_center(ib);
}
