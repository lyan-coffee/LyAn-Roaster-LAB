// Selected row of the System page (hardware keys: PWR next row, BOOT decrease, PLUS increase)
enum UiSysRowIdx : uint8_t {
    UI_SYS_ROW_HOT = 0,
    UI_SYS_ROW_IDLE,
    UI_SYS_ROW_BL,
    UI_SYS_ROW_UNIT,
    UI_SYS_ROW_SOUND,
    UI_SYS_ROWS
};

static uint8_t   g_uiSysRow = 0;
static lv_obj_t *g_uiSysCards[UI_SYS_ROWS] = {nullptr};
static lv_obj_t *g_uiSysList = nullptr;
static uint32_t  g_uiSysLastStepMs = 0;

// Preview one chirp when volume is adjusted / unmuted (does not interrupt a playing sound, silent when muted)
static inline void uiSysSoundPreview() {
#if CUE_ENABLE
    if (!g_uiSnap.soundMuted && g_alarm_sound == ALARM_SND_OFF) g_alarm_sound = ALARM_SND_WAKE;
#endif
}

static inline void uiSysApplyStep(uint8_t row, int delta) {
    intptr_t d = delta;
    if (row == UI_SYS_ROW_HOT) {
        int next = static_cast<int>(g_uiSnap.overheatC) + delta * 5;
        if (next < 220) next = 220;
        if (next > 260) next = 260;
        g_uiSnap.overheatC = static_cast<uint16_t>(next);
        if (g_uiOps.setOverheatC) g_uiOps.setOverheatC(g_uiSnap.overheatC);
    } else if (row == UI_SYS_ROW_IDLE) {
        static const uint8_t kSteps[6] = {0, 1, 3, 5, 10, 15};
        int idx = 3;
        for (int i = 0; i < 6; ++i) if (kSteps[i] == g_uiSnap.idleMin) { idx = i; break; }
        idx += static_cast<int>(d);
        if (idx < 0) idx = 0;
        if (idx > 5) idx = 5;
        g_uiSnap.idleMin = kSteps[idx];
        if (g_uiOps.setIdleMin) g_uiOps.setIdleMin(g_uiSnap.idleMin);
    } else if (row == UI_SYS_ROW_BL) {
        static const uint8_t kBlSteps[5] = {50, 63, 75, 88, 100};
        int idx = uiBlLevelIndex(g_uiSnap.brightnessPct) + static_cast<int>(d);
        if (idx < 0) idx = 0;
        if (idx > 4) idx = 4;
        g_uiSnap.brightnessPct = kBlSteps[idx];
        if (g_uiOps.setBrightnessPct) g_uiOps.setBrightnessPct(g_uiSnap.brightnessPct);
    } else if (row == UI_SYS_ROW_UNIT) {
        // Temperature unit: "-" = °C, "+" = °F (the core still works in °C, only the display changes)
        if (delta != 0) {
            g_uiSnap.unitF = (delta > 0);
            if (g_uiOps.setTempUnitF) g_uiOps.setTempUnitF(g_uiSnap.unitF);
        }
    } else if (row == UI_SYS_ROW_SOUND) {
        // Master volume: hardware BOOT / PLUS = ±10%; when muted PLUS unmutes, BOOT does nothing
        if (g_uiSnap.soundMuted) {
            if (delta > 0) { g_uiSnap.soundMuted = false; if (g_uiOps.setSoundMuted) g_uiOps.setSoundMuted(false); uiSysSoundPreview(); }
        } else if (delta != 0) {
            int v = static_cast<int>(g_uiSnap.volumePct) + delta * 10;
            if (v < UI_VOL_MIN_PCT) v = UI_VOL_MIN_PCT;
            if (v > 100) v = 100;
            g_uiSnap.volumePct = static_cast<uint8_t>(v);
            if (g_uiOps.setVolumePct) g_uiOps.setVolumePct(g_uiSnap.volumePct, true);
            uiSysSoundPreview();
        }
    }
    uiSystemRefreshLabels();
}

static inline void uiSysRefreshSel() {
    for (int i = 0; i < UI_SYS_ROWS; ++i) {
        if (!g_uiSysCards[i]) continue;
        const bool on = (i == g_uiSysRow);
        // Cards have no colored border: the selected row (hardware keys) gets a 2 px cream border, others a 1 px neutral border
        lv_obj_set_style_border_color(g_uiSysCards[i], lv_color_hex(on ? UI_HEX_TEXT : UI_HEX_BORDER), LV_PART_MAIN);
        lv_obj_set_style_border_width(g_uiSysCards[i], on ? 2 : 1, LV_PART_MAIN);
    }
    if (g_uiSysCards[g_uiSysRow]) lv_obj_scroll_to_view(g_uiSysCards[g_uiSysRow], LV_ANIM_OFF);
}

// +/- buttons: act at once on touch (PRESSED) and repeat while held; double input blocked for 150 ms. Does not depend on "release inside the button" like CLICKED
static void uiSysBtnCb(lv_event_t *e) {
    const lv_event_code_t code = lv_event_get_code(e);
    const uint32_t now = millis();
    if (code == LV_EVENT_PRESSED && (now - g_uiSysLastStepMs) < 150) return;
    g_uiSysLastStepMs = now;
    const intptr_t packed = reinterpret_cast<intptr_t>(lv_event_get_user_data(e));   // row*4 + (delta+1)
    const uint8_t row = static_cast<uint8_t>(packed >> 2);
    const int delta = static_cast<int>(packed & 3) - 1;
    g_uiSysRow = row;
    uiSysApplyStep(row, delta);
    uiSysRefreshSel();
}

// System page hardware keys: nextRow = PWR; delta = BOOT(-1) / PLUS(+1)
static inline void uiSystemHardwareBtn(int delta, bool nextRow) {
    if (nextRow) g_uiSysRow = (g_uiSysRow + 1) % UI_SYS_ROWS;
    else         uiSysApplyStep(g_uiSysRow, delta);
    uiSysRefreshSel();
}

